/**
 * PBP 安全层的密码学原语：HMAC-SHA256 签名。
 *
 * <p>本轮只移植签名的最小用例，纯 TS 实现，不引 node:crypto，浏览器与 Node 共用同一份代码；
 * 加密原语（ChaCha20-Poly1305 等）不在本次范围内。</p>
 */

