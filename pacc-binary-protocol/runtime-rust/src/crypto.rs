//!
//! 运行时要零第三方依赖，而 std 里没有哈希/HMAC，所以按 FIPS 180-4 与 RFC 2104
//! 直接实现。这里只做签名所需的两个原语；ChaCha20-Poly1305 等加密原语 Rust 侧
//! 暂未落地（Java 侧已有，本 crate 只对齐互操作向量用到的部分）。

